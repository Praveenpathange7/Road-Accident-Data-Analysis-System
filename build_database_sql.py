"""Build the complete MySQL schema and seed data from the bundled CSV files."""
import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
OUTPUT = ROOT / "road_accident_database.sql"


def read_csv(filename):
    with (DATA / filename).open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def quote(value):
    if value is None or value == "":
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    annual = read_csv("india_annual_trends_2015_2024.csv")
    state_trends = read_csv("state_accidents_2015_2024.csv")
    casualties = read_csv("state_casualties_2017_2023.csv")
    demo_2022 = read_csv("india_road_accidents_2022.csv")

    if len(state_trends) != 36 or len(demo_2022) != 36:
        raise ValueError("Expected complete accident data for all 36 States and Union Territories.")

    casualty_by_location = {row["location"]: row for row in casualties}
    snapshot_by_location = {row["location"]: row for row in demo_2022}
    for row in state_trends:
        snapshot = snapshot_by_location[row["location"]]
        casualty_row = casualty_by_location[row["location"]]
        checks = {
            "accidents_reported": row["2022"],
            "persons_killed": casualty_row["2022_killed"],
            "persons_injured": casualty_row["2022_injured"],
        }
        if any(checks[column] != snapshot[column] for column in checks):
            raise ValueError(f"The 2022 source files do not agree for {row['location']}.")

    locations = [(1, "India", "COUNTRY", None)]
    locations.extend(
        (index + 2, row["location"], row["location_type"], 1)
        for index, row in enumerate(state_trends)
    )

    statements = [
        "-- Generated by build_database_sql.py from the bundled CSV files.",
        "-- This seed contains aggregate totals, not incident-level crash records.",
        "-- Run with: mysql -u YOUR_USER -p < road_accident_database.sql",
        "CREATE DATABASE IF NOT EXISTS road_accident_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;",
        "USE road_accident_db;",
        """
CREATE TABLE IF NOT EXISTS locations (
  location_id INT PRIMARY KEY,
  location_name VARCHAR(120) NOT NULL UNIQUE,
  location_type ENUM('COUNTRY','STATE','UT','DISTRICT','CITY') NOT NULL,
  parent_location_id INT NULL,
  CONSTRAINT fk_locations_parent FOREIGN KEY (parent_location_id) REFERENCES locations(location_id)
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS data_sources (
  source_id INT PRIMARY KEY,
  publisher VARCHAR(180) NOT NULL,
  title VARCHAR(255) NOT NULL,
  source_url VARCHAR(600) NOT NULL,
  data_year SMALLINT NULL,
  accessed_on DATE NOT NULL,
  notes TEXT NULL
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS road_types (
  road_type_id INT PRIMARY KEY,
  road_type_name VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS vehicle_types (
  vehicle_type_id INT PRIMARY KEY,
  vehicle_type_name VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS weather_conditions (
  weather_id INT PRIMARY KEY,
  weather_name VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS severity_types (
  severity_id INT PRIMARY KEY,
  severity_name VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS accident_statistics (
  statistic_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  location_id INT NOT NULL,
  source_id INT NOT NULL,
  road_type_id INT NOT NULL DEFAULT 1,
  statistic_year SMALLINT NOT NULL,
  accidents_reported INT UNSIGNED NULL,
  persons_killed INT UNSIGNED NULL,
  persons_injured INT UNSIGNED NULL,
  UNIQUE KEY uq_location_year_road_source (location_id, statistic_year, road_type_id, source_id),
  KEY ix_stats_year (statistic_year),
  CONSTRAINT fk_stats_location FOREIGN KEY (location_id) REFERENCES locations(location_id),
  CONSTRAINT fk_stats_source FOREIGN KEY (source_id) REFERENCES data_sources(source_id),
  CONSTRAINT fk_stats_road_type FOREIGN KEY (road_type_id) REFERENCES road_types(road_type_id)
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS accident_records (
  accident_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  source_id INT NOT NULL,
  location_id INT NULL,
  accident_datetime DATETIME NULL,
  road_type_id INT NULL,
  weather_id INT NULL,
  severity_id INT NULL,
  persons_killed SMALLINT UNSIGNED NULL,
  persons_injured SMALLINT UNSIGNED NULL,
  latitude DECIMAL(9,6) NULL,
  longitude DECIMAL(9,6) NULL,
  source_record_ref VARCHAR(150) NULL,
  notes TEXT NULL,
  CONSTRAINT fk_record_source FOREIGN KEY (source_id) REFERENCES data_sources(source_id),
  CONSTRAINT fk_record_location FOREIGN KEY (location_id) REFERENCES locations(location_id),
  CONSTRAINT fk_record_road FOREIGN KEY (road_type_id) REFERENCES road_types(road_type_id),
  CONSTRAINT fk_record_weather FOREIGN KEY (weather_id) REFERENCES weather_conditions(weather_id),
  CONSTRAINT fk_record_severity FOREIGN KEY (severity_id) REFERENCES severity_types(severity_id),
  KEY ix_record_datetime (accident_datetime),
  KEY ix_record_location (location_id)
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS accident_vehicles (
  accident_id BIGINT NOT NULL,
  vehicle_type_id INT NOT NULL,
  vehicle_count SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  PRIMARY KEY (accident_id, vehicle_type_id),
  CONSTRAINT fk_av_accident FOREIGN KEY (accident_id) REFERENCES accident_records(accident_id) ON DELETE CASCADE,
  CONSTRAINT fk_av_vehicle FOREIGN KEY (vehicle_type_id) REFERENCES vehicle_types(vehicle_type_id)
) ENGINE=InnoDB;""",
        """
CREATE TABLE IF NOT EXISTS import_batches (
  batch_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  source_id INT NOT NULL,
  imported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  file_name VARCHAR(255) NULL,
  rows_loaded INT UNSIGNED NOT NULL DEFAULT 0,
  rows_rejected INT UNSIGNED NOT NULL DEFAULT 0,
  import_notes TEXT NULL,
  CONSTRAINT fk_batch_source FOREIGN KEY (source_id) REFERENCES data_sources(source_id)
) ENGINE=InnoDB;""",
        "INSERT IGNORE INTO locations (location_id,location_name,location_type,parent_location_id) VALUES\n"
        + ",\n".join(
            "(" + ",".join(quote(value) for value in location) + ")"
            for location in locations
        )
        + ";",
        """INSERT IGNORE INTO data_sources
(source_id,publisher,title,source_url,data_year,accessed_on,notes) VALUES
(1,'Ministry of Road Transport and Highways / Government of India',
 'India annual road accident totals, 2015-2024',
 'https://sansad.in/getFile/loksabhaquestions/annex/187/AU4505_smjOzM.pdf?source=pqals',
 2024,'2026-10-26','National totals reproduced in Lok Sabha Unstarred Question 4505.'),
(2,'PRS India / Ministry of Road Transport and Highways',
 'State and Union Territory road accident counts, 2015-2024',
 'https://prsindia.org/budgets/parliament/demand-for-grants-2026-27-analysis-road-transport-and-highways',
 2024,'2026-10-26','State/UT counts from state_accidents_2015_2024.csv. Casualty values are joined from the cited sources below.'),
(3,'Government of India, Lok Sabha',
 'State and Union Territory road accident casualties, 2017-2019',
 'https://sansad.in/getFile/loksabhaquestions/annex/1711/AU57.pdf?source=pqals',
 2019,'2026-10-26','Persons killed and injured from state_casualties_2017_2023.csv.'),
(4,'Ministry of Road Transport and Highways',
 'State and Union Territory road accident casualties, 2020-2023',
 'https://morth.gov.in/backend/documents/uploaded/Road-Accident-in-India-2023-Publications.pdf',
 2023,'2026-10-26','Persons killed and injured from state_casualties_2017_2023.csv.');""",
        "INSERT IGNORE INTO road_types (road_type_id,road_type_name) VALUES "
        "(1,'All road categories'),(2,'National Highway'),(3,'State Highway'),(4,'Other Road');",
        "INSERT IGNORE INTO vehicle_types (vehicle_type_id,vehicle_type_name) VALUES "
        "(1,'Two-wheeler'),(2,'Car or light motor vehicle'),(3,'Bus'),(4,'Truck or lorry'),"
        "(5,'Bicycle'),(6,'Auto-rickshaw'),(7,'Pedestrian'),(8,'Other or unknown');",
        "INSERT IGNORE INTO weather_conditions (weather_id,weather_name) VALUES "
        "(1,'Not reported'),(2,'Clear'),(3,'Rain'),(4,'Fog'),(5,'Other');",
        "INSERT IGNORE INTO severity_types (severity_id,severity_name) VALUES "
        "(1,'Fatal accident'),(2,'Injury accident'),(3,'Non-injury accident'),(4,'Not reported');",
    ]

    statistics = []
    for row in annual:
        statistics.append(
            (1, 1, 1, int(row["year"]), int(row["accidents_reported"]),
             int(row["persons_killed"]), int(row["persons_injured"]))
        )

    for location_id, row in enumerate(state_trends, start=2):
        casualty_row = casualty_by_location[row["location"]]
        for year in range(2015, 2025):
            accidents = row[str(year)]
            if not accidents:
                continue
            killed = casualty_row.get(f"{year}_killed", "")
            injured = casualty_row.get(f"{year}_injured", "")
            statistics.append(
                (location_id, 2, 1, year, int(accidents),
                 int(killed) if killed else None,
                 int(injured) if injured else None)
            )

    values = ",\n".join(
        "(" + ",".join(quote(value) for value in statistic) + ")"
        for statistic in statistics
    )
    statements.extend([
        "-- Includes all available national totals and State/UT annual totals.",
        "-- NULL casualty values mean the source did not publish a comparable figure.",
        "INSERT IGNORE INTO accident_statistics "
        "(location_id,source_id,road_type_id,statistic_year,accidents_reported,persons_killed,persons_injured) "
        "VALUES\n" + values + ";",
        """
-- Query shape used by app.py.
SELECT l.location_name AS location, l.location_type,
  s.statistic_year AS year, s.accidents_reported, s.persons_killed,
  s.persons_injured
FROM accident_statistics s
JOIN locations l ON l.location_id=s.location_id
WHERE l.location_type IN ('COUNTRY','STATE','UT')
  AND s.road_type_id=1
ORDER BY l.location_type,l.location_name,s.statistic_year;""",
    ])

    OUTPUT.write_text("\n\n".join(statements) + "\n", encoding="utf-8")
    print(f"Wrote {len(statistics)} annual statistics rows to {OUTPUT.name}.")


if __name__ == "__main__":
    main()
